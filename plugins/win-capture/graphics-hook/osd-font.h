// Character index lookup - returns index into osd_font_data, or -1 if not supported
static inline int osd_font_get_index(char c)
{
	if (c == ' ')
		return 0;
	if (c >= '0' && c <= '9')
		return 1 + (c - '0');
	if (c == ':')
		return 11;
	if (c == 'A')
		return 17;
	if (c == 'C')
		return 12;
	if (c == 'E')
		return 13;
	if (c == 'I')
		return 14;
	if (c == 'L')
		return 15;
	if (c == 'M')
		return 18;
	if (c == 'R')
		return 16;
	if (c == 'V')
		return 19;
	return -1; // Unsupported character
}
